// Change Language function
function setLanguage(lang) {
    localStorage.setItem('preferred_lang', lang);
    document.documentElement.lang = lang;
    
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });
}

// Scroll to admission form with pre-selected course
function scrollToAdmission(courseName) {
    const courseSelect = document.getElementById('courseSelect');
    if (courseSelect) {
        courseSelect.value = courseName;
    }
    document.getElementById('admission').scrollIntoView({ behavior: 'smooth' });
}

document.addEventListener('DOMContentLoaded', () => {
    // Language Switcher Logic
    const langSelect = document.getElementById('languageSelect');
    const savedLang = localStorage.getItem('preferred_lang') || 'uz';
    langSelect.value = savedLang;
    setLanguage(savedLang);

    langSelect.addEventListener('change', (e) => {
        setLanguage(e.target.value);
    });

    // Smooth Scrolling for Navbar links
    document.querySelectorAll('a.nav-link').forEach(anchor => {
        anchor.addEventListener('click', function(e) {
            const targetId = this.getAttribute('href');
            if(targetId.startsWith('#')) {
                e.preventDefault();
                const targetElement = document.querySelector(targetId);
                if(targetElement) {
                    targetElement.scrollIntoView({ behavior: 'smooth' });
                    // Close mobile menu if open
                    const navbarCollapse = document.getElementById('navbarNav');
                    if(navbarCollapse.classList.contains('show')) {
                        new bootstrap.Collapse(navbarCollapse).hide();
                    }
                }
            }
        });
    });

    // Back to top button logic
    const backToTopBtn = document.getElementById('backToTop');
    window.addEventListener('scroll', () => {
        if (window.scrollY > 300) {
            backToTopBtn.classList.remove('d-none');
        } else {
            backToTopBtn.classList.add('d-none');
        }
    });

    backToTopBtn.addEventListener('click', () => {
        window.scrollTo({ top: 0, behavior: 'smooth' });
    });

    // Form Validation and Success Notification
    const admissionForm = document.getElementById('admissionForm');
    const successAlert = document.getElementById('successAlert');

    admissionForm.addEventListener('submit', (e) => {
        e.preventDefault();
        
        const fullName = document.getElementById('fullName').value.trim();
        const phone = document.getElementById('phone').value.trim();
        const email = document.getElementById('email').value.trim();

        if (fullName === '' || phone === '' || email === '') {
            alert('Лутфан барча мажбурий майдонларни тўлдиринг!');
            return;
        }

        // Show success alert
        successAlert.classList.remove('d-none');
        admissionForm.reset();

        setTimeout(() => {
            successAlert.classList.add('d-none');
        }, 5000);
    });
});